import mongoose, { Schema, models, model } from "mongoose";

const SettingsSchema = new Schema(
  {
    siteName: { type: String, default: "Onesoftauto" },
    tagline: String,
    email: String,
    phone: String,
    address: String,
    calendlyUrl: String,
    socialLinks: [{ platform: String, url: String }],
    stats: [{ label: String, value: Number, suffix: String }],
    logoDark: { type: String, default: "/brand/logo-dark.png" },
    logoWhite: { type: String, default: "/brand/logo-light.png" },
    favicon: { type: String, default: "/logo/favicon.png" },
    appleTouchIcon: String,
    metaTitle: String,
    metaDescription: String,
    metaKeywords: [String],
    ogTitle: String,
    ogDescription: String,
    ogImage: String,
    ogType: { type: String, default: "website" },
    ogLocale: { type: String, default: "en_US" },
    twitterCard: { type: String, default: "summary_large_image" },
    twitterSite: String,
    twitterCreator: String,
    linkedinUrl: String,
    robotsIndex: { type: Boolean, default: true },
    heroEyebrow: String,
    heroHeadline: String,
    heroHeadlineAccent: String,
    heroSubcopy: String,
    aboutLead: String,
    aboutLeadEm: String,
    aboutPoints: [{ title: String, body: String }],
    processSubcopy: String,
    contactHeadline: String,
    contactSubcopy: String,
    whatsappUrl: String,
  },
  { timestamps: true }
);

export const Settings = models.Settings || model("Settings", SettingsSchema);
